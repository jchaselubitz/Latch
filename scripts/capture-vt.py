def write_case(name: str, spec: dict) -> None:
    cols = spec.get("cols", DEFAULT_COLS)
    rows = spec.get("rows", DEFAULT_ROWS)
    if shutil.which(spec["argv"][0]) is None:
        print("skip %s: %s not on PATH" % (name, spec["argv"][0]), file=sys.stderr)
        return

    data, resizes = record(
        spec["argv"],
        cwd=spec.get("cwd"),
        seconds=spec.get("seconds", 8.0),
        cols=cols,
        rows=rows,
        keys=spec.get("keys", ()),
        resize=spec.get("resize"),
        env=spec.get("env"),
    )
    if not data:
        print("skip %s: recorded no output" % name, file=sys.stderr)
        return

    case_dir = os.path.join(VT_DIR, name)
    os.makedirs(case_dir, exist_ok=True)
    with open(os.path.join(case_dir, "input.bin"), "wb") as handle:
        handle.write(data)

    meta = {
        "name": name,
        "description": spec["note"],
        "size": {"cols": cols, "rows": rows},
        "recorded": {
            "command": spec["argv"],
            "term": "xterm-256color",
            "platform": platform.system().lower(),
            "bytes": len(data),
        },
    }
    if resizes:
        meta["resizes"] = resizes
    if spec.get("notes"):
        meta["notes"] = spec["notes"]
    meta_path = os.path.join(case_dir, "meta.json")
    existing = {}
    if os.path.exists(meta_path):
        with open(meta_path, encoding="utf-8") as handle:
            existing = json.load(handle)
    # Hand-authored fields survive a re-record.
    for key in ("notes", "expected_from"):
        if key in existing:
            meta[key] = existing[key]
    with open(meta_path, "w", encoding="utf-8") as handle:
        json.dump(meta, handle, indent=2, ensure_ascii=False)
        handle.write("\n")
    print("wrote %s (%d bytes)" % (name, len(data)))


def main() -> int:
    cases = case_definitions()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("names", nargs="*", help="case names to record")
    parser.add_argument("--all", action="store_true", help="record every case")
    parser.add_argument("--list", action="store_true", help="list case names")
    args = parser.parse_args()

    if args.list:
        for name in sorted(cases):
            print(name)
        return 0

    selected = sorted(cases) if args.all else args.names
    if not selected:
        parser.print_usage(sys.stderr)
        return 2
    for name in selected:
        if name not in cases:
            print("unknown case: %s" % name, file=sys.stderr)
            return 2
        write_case(name, cases[name])
    return 0


if __name__ == "__main__":
    sys.exit(main())

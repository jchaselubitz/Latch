#!/usr/bin/env python3
"""Record VT fixture cases from a real PTY.

A recorded fixture with no recording tool is unreproducible, so the recorder
lives in the repo next to the fixtures it writes. Re-recording a case is::

    scripts/capture-vt.py claude-code-startup

and re-recording everything is::

    scripts/capture-vt.py --all

The point of recording rather than hand-writing escape sequences is fidelity:
hand-written sequences only test what the author already knew about. Claude Code
emits synchronized-output brackets, kitty keyboard flags, and OSC title updates
that nobody writes into a test by hand.

Each case becomes `fixtures/vt/<name>/` holding `input.bin` (the raw PTY output)
and `meta.json` (initial size, any resize applied partway, and provenance).
`expected.json` is authored by hand — it is an independent reading of the bytes,
not a dump of what an emulator produced, for the same reason the protocol
fixtures were not generated by the crate under test.
"""

from __future__ import annotations

import argparse
import errno
import fcntl
import json
import os
import platform
import pty
import select
import shutil
import struct
import sys
import termios
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VT_DIR = os.path.join(ROOT, "fixtures", "vt")

DEFAULT_COLS = 100
DEFAULT_ROWS = 30


def set_size(fd: int, cols: int, rows: int) -> None:
    fcntl.ioctl(fd, termios.TIOCSWINSZ, struct.pack("HHHH", rows, cols, 0, 0))


def record(
    argv,
    *,
    cwd=None,
    seconds=8.0,
    cols=DEFAULT_COLS,
    rows=DEFAULT_ROWS,
    keys=(),
    resize=None,
    env=None,
):
    """Run `argv` on a PTY and return (output_bytes, resizes).

    `keys` is a sequence of (delay_seconds, bytes) written to the PTY. `resize`
    is an optional (delay_seconds, cols, rows); the byte offset at which it
    landed is recorded so replay can apply it at the same point in the stream.
    """
    pid, fd = pty.fork()
    if pid == 0:
        child_env = {
            "TERM": "xterm-256color",
            "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
            "HOME": os.environ.get("HOME", "/tmp"),
            "LANG": "C.UTF-8",
            "LC_ALL": "C.UTF-8",
            # Recorded streams must not vary run to run more than the program
            # itself varies.
            "NO_COLOR": "",
        }
        child_env.pop("NO_COLOR")
        child_env.update(env or {})
        os.environ.clear()
        os.environ.update(child_env)
        if cwd:
            os.chdir(cwd)
        try:
            os.execvp(argv[0], argv)
        finally:
            os._exit(127)

    set_size(fd, cols, rows)

    out = bytearray()
    resizes = []
    pending_keys = list(keys)
    pending_resize = resize
    start = time.monotonic()
    deadline = start + seconds

    while time.monotonic() < deadline:
        now = time.monotonic() - start
        while pending_keys and now >= pending_keys[0][0]:
            os.write(fd, pending_keys.pop(0)[1])
        if pending_resize and now >= pending_resize[0]:
            _, new_cols, new_rows = pending_resize
            pending_resize = None
            resizes.append(
                {"at_byte": len(out), "cols": new_cols, "rows": new_rows}
            )
            set_size(fd, new_cols, new_rows)
        ready, _, _ = select.select([fd], [], [], 0.1)
        if not ready:
            continue
        try:
            chunk = os.read(fd, 65536)
        except OSError as exc:
            if exc.errno in (errno.EIO, errno.EBADF):
                break
            raise
        if not chunk:
            break
        out += chunk

    try:
        os.kill(pid, 9)
        os.waitpid(pid, 0)
    except OSError:
        pass
    try:
        os.close(fd)
    except OSError:
        pass

    return bytes(out), resizes


def sh(script: str) -> list:
    return ["bash", "--norc", "--noprofile", "-c", script]


# Scratch material some cases page through or dump.
def _scratch(name: str, content: str) -> str:
    path = os.path.join("/tmp", "latch-vt-" + name)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)
    return path


